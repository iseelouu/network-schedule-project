package network.schedule.model;

/**
 * Определяет тип зависимости между двумя работами проекта.
 */
public enum DependencyType {
    /**
     * Окончание предшествующей работы определяет начало следующей.
     */
    FINISH_TO_START,

    /**
     * Начало предшествующей работы определяет начало следующей.
     */
    START_TO_START,

    /**
     * Окончание предшествующей работы определяет окончание следующей.
     */
    FINISH_TO_FINISH,

    /**
     * Начало предшествующей работы определяет окончание следующей.
     */
    START_TO_FINISH
}
